// Refreshes packages/tok-ui/src/contributors.generated.ts from GitHub: the main developer plus every
// human contributor of the repository, with profile link and profile picture (embedded as a data: URI).
//
//   node scripts/update-contributors.mjs            (npm run contributors)
//   GITHUB_TOKEN=... node scripts/update-contributors.mjs   (avoids the anonymous API rate limit)
//
// Never breaks a build: if GitHub cannot be reached the existing file is kept (use --strict to fail instead).
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(rootDir, 'packages/tok-ui/src/contributors.generated.ts');
const REPO = 'TypesetOK/typesetok';
const MAIN_LOGIN = 'Amlaach';
const MAX_AVATAR_BYTES = 60 * 1024;
const strict = process.argv.includes('--strict');

const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'typesetok-contributors-script' };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

async function getJson(url) {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.json();
}

async function avatarDataUri(avatarUrl) {
  try {
    const url = new URL(avatarUrl);
    url.searchParams.set('s', '96');
    const res = await fetch(url, { headers: { 'User-Agent': headers['User-Agent'] } });
    const type = res.headers.get('content-type') || '';
    if (!res.ok || !type.startsWith('image/')) return '';
    const buf = Buffer.from(await res.arrayBuffer());
    return buf.length <= MAX_AVATAR_BYTES ? `data:${type};base64,${buf.toString('base64')}` : '';
  } catch {
    return '';
  }
}

async function describe(login, avatarUrl) {
  let name = login;
  try {
    const profile = await getJson(`https://api.github.com/users/${encodeURIComponent(login)}`);
    if (profile && typeof profile.name === 'string' && profile.name.trim()) name = profile.name.trim();
  } catch {
    // keep the login as the display name
  }
  return { login, name, url: `https://github.com/${login}`, avatar: avatarUrl ? await avatarDataUri(avatarUrl) : '' };
}

try {
  const list = await getJson(`https://api.github.com/repos/${REPO}/contributors?per_page=100`);
  const humans = list.filter((c) => c && c.type === 'User' && c.login.toLowerCase() !== MAIN_LOGIN.toLowerCase());
  const mainUser = await getJson(`https://api.github.com/users/${MAIN_LOGIN}`);
  const main = await describe(MAIN_LOGIN, mainUser.avatar_url);
  const contributors = [];
  for (const c of humans) contributors.push(await describe(c.login, c.avatar_url));

  const src = `// AUTO-GENERATED by scripts/update-contributors.mjs (npm run contributors). Do not edit by hand.
// Avatars are embedded as data: URIs because the app's CSP does not allow remote images.
export interface Contributor {
  login: string;
  name: string;
  url: string;
  /** data: URI of the GitHub profile picture, or '' (the About screen then shows an initial). */
  avatar: string;
}

export const MAIN_DEVELOPER: Contributor = ${JSON.stringify(main, null, 2)};

export const CONTRIBUTORS: Contributor[] = ${JSON.stringify(contributors, null, 2)};
`;
  fs.writeFileSync(outFile, src, 'utf8');
  console.log(`[contributors] wrote ${contributors.length} contributors + main developer to ${path.relative(rootDir, outFile)}`);
} catch (err) {
  console.warn(`[contributors] could not refresh from GitHub, keeping the existing file: ${err.message}`);
  if (strict) process.exit(1);
}
