//! Multi-Page Co-Pagination Engine with Automatic Overflow Splitting.
//!
//! Orchestrates coordinated page generation across parallel text streams (Gemara, Rashi, Tosafot):
//! - Tracks anchor dependencies between central text and commentaries.
//! - Detects commentary overflow or excessive lag on the current page.
//! - Automatically cuts central text at the optimal anchor boundary and pushes
//!   remaining central text and dependent commentaries to subsequent pages.
//! - Dynamically synthesizes L-shapes under early-terminating central text.
//! - Applies active vertical springs to align commentary headings with anchors.

use super::sync::{
    ActiveSyncResult, ActiveSynchronizer, AnchorKey, SyncRemedy, SynchronizerConfig,
};
use super::template::{SpreadMathematics, TemplateConfig};
use crate::engine::TypesettingEngine;
use crate::geometry::{LineBox, PageLayoutBox, PhysicalRect, TextFrameBox};
use std::collections::{HashMap, HashSet, VecDeque};
use tok_core::id::FractionalIndex;
use tok_core::model::ParagraphNode;
use tok_core::FlowId;

/// A central text paragraph (Gemara) containing one or more anchor phrases.
#[derive(Debug, Clone)]
pub struct CoPaginatedChunk {
    pub text: String,
    /// (anchor_key, exact search phrase in `text`)
    pub anchors: Vec<(AnchorKey, String)>,
}

/// A commentary paragraph (Rashi or Tosafot) attached to a specific central anchor.
#[derive(Debug, Clone)]
pub struct CoPaginatedCommentary {
    pub target_anchor: AnchorKey,
    pub text: String,
}

/// A complete multi-stream document input for co-pagination.
#[derive(Debug, Clone, Default)]
pub struct CoPaginationDocument {
    pub main_chunks: Vec<CoPaginatedChunk>,
    pub rashi_items: Vec<CoPaginatedCommentary>,
    pub tosafot_items: Vec<CoPaginatedCommentary>,
    pub additional_streams: HashMap<FlowId, Vec<CoPaginatedCommentary>>,
}

impl CoPaginationDocument {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn with_main(mut self, chunks: Vec<CoPaginatedChunk>) -> Self {
        self.main_chunks = chunks;
        self
    }

    pub fn with_rashi(mut self, rashi: Vec<CoPaginatedCommentary>) -> Self {
        self.rashi_items = rashi;
        self
    }

    pub fn with_tosafot(mut self, tosafot: Vec<CoPaginatedCommentary>) -> Self {
        self.tosafot_items = tosafot;
        self
    }

    pub fn with_stream(
        mut self,
        flow_id: impl Into<String>,
        items: Vec<CoPaginatedCommentary>,
    ) -> Self {
        let name = flow_id.into();
        match name.as_str() {
            "rashi" => self.rashi_items.extend(items),
            "tosafot" => self.tosafot_items.extend(items),
            _ => self
                .additional_streams
                .entry(FlowId::new(&name))
                .or_default()
                .extend(items),
        }
        self
    }

    pub fn add_commentary(&mut self, flow_id: impl Into<String>, item: CoPaginatedCommentary) {
        let name = flow_id.into();
        match name.as_str() {
            "rashi" => self.rashi_items.push(item),
            "tosafot" => self.tosafot_items.push(item),
            _ => self
                .additional_streams
                .entry(FlowId::new(&name))
                .or_default()
                .push(item),
        }
    }
}

/// Layout details for a single page generated by the co-pagination engine.
#[derive(Debug, Clone)]
pub struct CoPaginatedPage {
    pub page_number: usize,
    pub page_layout: PageLayoutBox,
    pub math: SpreadMathematics,
    pub gemara_lines_count: usize,
    pub rashi_lines_count: usize,
    pub tosafot_lines_count: usize,
    pub rashi_expanded_lines_count: usize,
    pub sync_results: Vec<ActiveSyncResult>,
    pub stream_lines_count: HashMap<FlowId, usize>,
}

/// Result of multi-page co-pagination across the entire document.
#[derive(Debug, Clone)]
pub struct CoPaginationResult {
    pub pages: Vec<CoPaginatedPage>,
    pub total_pages: usize,
    pub total_gemara_lines: usize,
    pub total_rashi_lines: usize,
    pub total_tosafot_lines: usize,
    pub total_stream_lines: HashMap<FlowId, usize>,
    pub all_anchors_remedied: bool,
}

/// Determines the optimal split line count for a paragraph across consecutive pages,
/// strictly enforcing orphan control (minimum lines on current page) and widow control
/// (minimum lines carried over to next page).
pub fn calculate_typographic_split(
    total_lines: usize,
    available_lines: usize,
    orphan_threshold: usize,
    widow_threshold: usize,
) -> Option<usize> {
    if total_lines <= available_lines {
        return Some(total_lines);
    }
    if available_lines < orphan_threshold {
        return None;
    }
    let mut take = available_lines;
    let remainder = total_lines - take;

    if remainder < widow_threshold {
        let needed_for_widow = widow_threshold - remainder;
        if take >= orphan_threshold + needed_for_widow {
            take -= needed_for_widow;
        } else {
            return None;
        }
    }

    if take >= orphan_threshold && total_lines - take >= widow_threshold {
        Some(take)
    } else {
        None
    }
}

pub struct CoPaginationEngine;

impl CoPaginationEngine {
    pub const MAX_PAGES_SAFETY: usize = 500;

    /// Co-paginates an entire multi-stream document across consecutive book pages,
    /// automatically splitting central text when commentary overflows and carrying over
    /// remaining content to subsequent pages.
    pub fn co_paginate(
        config: &TemplateConfig,
        sync_config: &SynchronizerConfig,
        doc: &CoPaginationDocument,
        engine: &TypesettingEngine,
    ) -> CoPaginationResult {
        let mut remaining_chunks: VecDeque<CoPaginatedChunk> =
            doc.main_chunks.iter().cloned().collect();
        let mut remaining_rashi: VecDeque<CoPaginatedCommentary> =
            doc.rashi_items.iter().cloned().collect();
        let mut remaining_tosafot: VecDeque<CoPaginatedCommentary> =
            doc.tosafot_items.iter().cloned().collect();
        let mut remaining_additional: HashMap<FlowId, VecDeque<CoPaginatedCommentary>> = doc
            .additional_streams
            .iter()
            .map(|(k, v)| (k.clone(), v.iter().cloned().collect()))
            .collect();

        let mut pages = Vec::new();
        let mut total_gemara_lines = 0;
        let mut total_rashi_lines = 0;
        let mut total_tosafot_lines = 0;
        let mut total_stream_lines: HashMap<FlowId, usize> = HashMap::new();
        let mut all_anchors_remedied = true;
        let mut seen_anchors: HashSet<AnchorKey> = HashSet::new();

        let mut page_number = 1;

        while (!remaining_chunks.is_empty()
            || !remaining_rashi.is_empty()
            || !remaining_tosafot.is_empty()
            || remaining_additional.values().any(|q| !q.is_empty()))
            && page_number <= Self::MAX_PAGES_SAFETY
        {
            let math = SpreadMathematics::for_page(config, page_number);

            let max_gemara_lines =
                (math.content_height_pt / config.main_line_height).floor() as usize;
            let max_commentary_lines =
                (math.content_height_pt / config.commentary_line_height).floor() as usize;

            // 1. Greedily determine which Gemara chunks fit on this page without overflowing commentary
            let mut page_chunks = Vec::new();
            let mut tentative_gemara_lines: Vec<LineBox> = Vec::new();
            let mut tentative_gemara_anchors: HashMap<AnchorKey, (usize, f32)> = HashMap::new();
            let mut current_g_y = 0.0;

            // Commentary capacity estimation derived from actual column widths and font metrics
            let mut page_rashi_chars = 0;
            let mut page_tosafot_chars = 0;
            let mut page_addl_chars: HashMap<FlowId, usize> = HashMap::new();
            let rashi_chars_per_line = (math.inner_column_width_pt
                / (config.commentary_font_size * 0.52))
                .max(20.0) as usize;
            let tosafot_chars_per_line = (math.outer_column_width_pt
                / (config.commentary_font_size * 0.52))
                .max(20.0) as usize;
            let max_rashi_chars_approx = max_commentary_lines * rashi_chars_per_line;
            let max_tosafot_chars_approx = max_commentary_lines * tosafot_chars_per_line;

            while let Some(chunk) = remaining_chunks.pop_front() {
                let p_node = ParagraphNode::new(
                    FractionalIndex::new(format!("g_{}_{}", page_number, page_chunks.len())),
                    "gemara",
                    &chunk.text,
                );
                let main_profile = math.create_measure_profile(config, "main", None);
                let chunk_lines = engine.typeset_paragraph_shaped(
                    &p_node,
                    &config.main_font_family,
                    &main_profile,
                    config.main_font_size,
                    config.main_line_height,
                );

                if tentative_gemara_lines.len() + chunk_lines.len() > max_gemara_lines {
                    let available_lines =
                        max_gemara_lines.saturating_sub(tentative_gemara_lines.len());
                    if !tentative_gemara_lines.is_empty() && available_lines < 2 {
                        // Orphan prevention: push chunk back and finish page
                        remaining_chunks.push_front(chunk);
                        break;
                    }

                    if let Some(take) =
                        calculate_typographic_split(chunk_lines.len(), available_lines, 2, 2)
                    {
                        let mut this_lines = chunk_lines[..take].to_vec();
                        let remainder_lines = &chunk_lines[take..];

                        let mut this_anchors = Vec::new();
                        let mut remainder_anchors = Vec::new();
                        for (a_key, phrase) in chunk.anchors {
                            let in_this = this_lines.iter().any(|l| l.text.contains(&phrase));
                            let in_rem = remainder_lines.iter().any(|l| l.text.contains(&phrase));
                            if in_this {
                                this_anchors.push((a_key.clone(), phrase.clone()));
                            }
                            if in_rem || (!in_this && !in_rem) {
                                remainder_anchors.push((a_key, phrase));
                            }
                        }

                        for (a_key, phrase) in &this_anchors {
                            let mut anchor_line_rel = 0;
                            for (l_idx, line) in this_lines.iter().enumerate() {
                                if line.text.contains(phrase) {
                                    anchor_line_rel = l_idx;
                                    break;
                                }
                            }
                            let abs_l = tentative_gemara_lines.len() + anchor_line_rel;
                            let abs_y = current_g_y
                                + (anchor_line_rel as f32 + 1.0) * config.main_line_height;
                            tentative_gemara_anchors.insert(a_key.clone(), (abs_l, abs_y));
                        }

                        let base_idx = tentative_gemara_lines.len();
                        for (idx, line) in this_lines.iter_mut().enumerate() {
                            line.line_index = base_idx + idx;
                            line.baseline_y += current_g_y;
                        }
                        tentative_gemara_lines.extend(this_lines.iter().cloned());
                        page_chunks.push(CoPaginatedChunk {
                            text: this_lines
                                .iter()
                                .map(|l| l.text.as_str())
                                .collect::<Vec<_>>()
                                .join(" "),
                            anchors: this_anchors,
                        });

                        let remainder_text = remainder_lines
                            .iter()
                            .map(|l| l.text.as_str())
                            .collect::<Vec<_>>()
                            .join(" ");
                        remaining_chunks.push_front(CoPaginatedChunk {
                            text: remainder_text,
                            anchors: remainder_anchors,
                        });
                        break;
                    } else if !tentative_gemara_lines.is_empty() {
                        remaining_chunks.push_front(chunk);
                        break;
                    }
                }

                // Check commentary demand for this chunk's anchors
                let mut chunk_rashi_demand = 0;
                let mut chunk_tosafot_demand = 0;
                let mut chunk_addl_demand: HashMap<FlowId, usize> = HashMap::new();
                for (a_key, _) in &chunk.anchors {
                    for r in remaining_rashi.iter().filter(|r| r.target_anchor == *a_key) {
                        chunk_rashi_demand += r.text.len();
                    }
                    for t in remaining_tosafot
                        .iter()
                        .filter(|t| t.target_anchor == *a_key)
                    {
                        chunk_tosafot_demand += t.text.len();
                    }
                    for (fid, queue) in &remaining_additional {
                        let dem: usize = queue
                            .iter()
                            .filter(|c| c.target_anchor == *a_key)
                            .map(|c| c.text.len())
                            .sum();
                        *chunk_addl_demand.entry(fid.clone()).or_insert(0) += dem;
                    }
                }

                let mut overflow_any_addl = false;
                for (fid, dem) in &chunk_addl_demand {
                    let col_w = math
                        .columns
                        .iter()
                        .find(|c| c.stream_id == fid.0)
                        .map(|c| c.width_pt)
                        .unwrap_or(math.inner_column_width_pt);
                    let chars_per_line =
                        (col_w / (config.commentary_font_size * 0.55)).max(20.0) as usize;
                    let max_chars = max_commentary_lines * chars_per_line;
                    let curr_chars = page_addl_chars.get(fid).copied().unwrap_or(0);
                    if curr_chars + dem > max_chars {
                        overflow_any_addl = true;
                        break;
                    }
                }

                // If adding this chunk causes unbridgeable commentary overflow, split and push to next page
                if !page_chunks.is_empty()
                    && (page_rashi_chars + chunk_rashi_demand > max_rashi_chars_approx
                        || page_tosafot_chars + chunk_tosafot_demand > max_tosafot_chars_approx
                        || overflow_any_addl)
                {
                    remaining_chunks.push_front(chunk);
                    break;
                }

                // Record anchor positions within chunk
                for (a_key, phrase) in &chunk.anchors {
                    let mut anchor_line_rel = 0;
                    for (l_idx, line) in chunk_lines.iter().enumerate() {
                        if line.text.contains(phrase) {
                            anchor_line_rel = l_idx;
                            break;
                        }
                    }
                    let abs_l = tentative_gemara_lines.len() + anchor_line_rel;
                    let abs_y =
                        current_g_y + (anchor_line_rel as f32 + 1.0) * config.main_line_height;
                    tentative_gemara_anchors.insert(a_key.clone(), (abs_l, abs_y));
                }

                let mut positioned_chunk_lines = chunk_lines;
                let base_idx = tentative_gemara_lines.len();
                for (idx, line) in positioned_chunk_lines.iter_mut().enumerate() {
                    line.line_index = base_idx + idx;
                    line.baseline_y += current_g_y;
                }
                current_g_y += positioned_chunk_lines.len() as f32 * config.main_line_height;
                tentative_gemara_lines.extend(positioned_chunk_lines);
                page_rashi_chars += chunk_rashi_demand;
                page_tosafot_chars += chunk_tosafot_demand;
                for (fid, dem) in chunk_addl_demand {
                    *page_addl_chars.entry(fid).or_insert(0) += dem;
                }
                page_chunks.push(chunk);

                // Stop adding if Gemara is at or near full column
                if tentative_gemara_lines.len() >= max_gemara_lines {
                    break;
                }
            }

            // Gemara height on this page
            let gemara_h = tentative_gemara_lines.len() as f32 * config.main_line_height;

            // 2. Synthesize dynamic L-shape profile for Rashi on this page
            let rashi_profile = math.create_measure_profile(config, "rashi", Some(gemara_h));
            let tosafot_profile = math.create_measure_profile(config, "tosafot", None);

            let rashi_narrow_lines = (gemara_h / config.commentary_line_height).ceil() as usize;

            // 3. Typeset Rashi for anchors assigned to this page, plus any carry-overs
            let mut page_rashi_lines: Vec<LineBox> = Vec::new();
            let mut rashi_anchor_positions: HashMap<AnchorKey, f32> = HashMap::new();
            let mut rashi_line_counter = 0;
            let mut sync_results = Vec::new();

            // Record all anchors appearing on this page
            for k in tentative_gemara_anchors.keys() {
                seen_anchors.insert(k.clone());
            }

            // Collect Rashi items matching this page's anchors or earlier carry-overs
            let mut this_page_rashi = Vec::new();
            let mut unplaced_rashi = VecDeque::new();

            while let Some(item) = remaining_rashi.pop_front() {
                let is_anchor_here = tentative_gemara_anchors.contains_key(&item.target_anchor);
                let is_carry_over = seen_anchors.contains(&item.target_anchor);
                if is_anchor_here
                    || is_carry_over
                    || (page_chunks.is_empty() && this_page_rashi.len() < max_commentary_lines)
                {
                    this_page_rashi.push(item);
                } else {
                    unplaced_rashi.push_back(item);
                }
            }
            remaining_rashi = unplaced_rashi;

            // Typeset each Rashi paragraph with profile & active synchronization
            let mut current_rashi_y = 0.0f32;
            for (p_idx, item) in this_page_rashi.into_iter().enumerate() {
                let start_line = rashi_line_counter;
                let natural_y = current_rashi_y.max(start_line as f32 * config.commentary_line_height);

                // Create paragraph-offset profile
                let p_profile = if !rashi_profile.is_uniform() {
                    if start_line < rashi_narrow_lines {
                        let remaining_narrow = rashi_narrow_lines - start_line;
                        let exp_w =
                            math.inner_column_width_pt + math.main_column_width_pt + math.gutter_pt;
                        crate::knuth_plass::MeasureProfile::l_shape(
                            remaining_narrow,
                            math.inner_column_width_pt,
                            exp_w,
                        )
                    } else {
                        let exp_w =
                            math.inner_column_width_pt + math.main_column_width_pt + math.gutter_pt;
                        crate::knuth_plass::MeasureProfile::uniform(exp_w)
                    }
                } else {
                    crate::knuth_plass::MeasureProfile::uniform(math.inner_column_width_pt)
                };

                let p_node = ParagraphNode::new(
                    FractionalIndex::new(format!("r_{}_{}", page_number, p_idx)),
                    "rashi",
                    &item.text,
                );
                let mut p_lines = engine.typeset_paragraph_shaped(
                    &p_node,
                    &config.commentary_font_family,
                    &p_profile,
                    config.commentary_font_size,
                    config.commentary_line_height,
                );

                if rashi_line_counter + p_lines.len() > max_commentary_lines {
                    let available_lines = max_commentary_lines.saturating_sub(rashi_line_counter);
                    if let Some(take) =
                        calculate_typographic_split(p_lines.len(), available_lines, 2, 2)
                    {
                        let this_lines = p_lines[..take].to_vec();
                        let remainder_lines = &p_lines[take..];
                        let remainder_text = remainder_lines
                            .iter()
                            .map(|l| l.text.as_str())
                            .collect::<Vec<_>>()
                            .join(" ");
                        remaining_rashi.push_front(CoPaginatedCommentary {
                            target_anchor: item.target_anchor.clone(),
                            text: remainder_text,
                        });
                        p_lines = this_lines;
                    } else if !page_rashi_lines.is_empty() {
                        remaining_rashi.push_front(item);
                        break;
                    }
                }

                // Offset paragraph-local baselines by current_rashi_y
                for (idx, line) in p_lines.iter_mut().enumerate() {
                    line.line_index = start_line + idx;
                    line.baseline_y += natural_y;
                }

                // Evaluate active synchronization
                let mut spring_pt = 0.0;
                if let Some(&(_, g_y)) = tentative_gemara_anchors.get(&item.target_anchor) {
                    let sync = ActiveSynchronizer::evaluate_and_remedy(
                        sync_config,
                        &item.target_anchor,
                        g_y,
                        "rashi",
                        natural_y,
                    );
                    if let SyncRemedy::VerticalSpringApplied { spring_pt: s } = sync.remedy {
                        let full_align_spring = (g_y - natural_y).max(s);
                        let max_room = (math.content_height_pt
                            - (natural_y + p_lines.len() as f32 * config.commentary_line_height))
                            .max(0.0);
                        spring_pt = full_align_spring.min(max_room);
                        ActiveSynchronizer::apply_spring_offset(&mut p_lines, spring_pt);
                    }
                    if matches!(
                        sync.remedy,
                        SyncRemedy::ExcessiveLead { .. } | SyncRemedy::RequirePageCut { .. }
                    ) {
                        all_anchors_remedied = false;
                    }
                    sync_results.push(sync);
                }

                rashi_anchor_positions.insert(item.target_anchor.clone(), natural_y + spring_pt);
                current_rashi_y = p_lines
                    .last()
                    .map(|l| l.baseline_y)
                    .unwrap_or(natural_y + spring_pt);
                rashi_line_counter += p_lines.len();
                page_rashi_lines.extend(p_lines);
            }

            // 4. Typeset Tosafot for this page
            let mut page_tosafot_lines: Vec<LineBox> = Vec::new();
            let mut tosafot_line_counter = 0;
            let mut this_page_tosafot = Vec::new();
            let mut unplaced_tosafot = VecDeque::new();

            while let Some(item) = remaining_tosafot.pop_front() {
                let is_anchor_here = tentative_gemara_anchors.contains_key(&item.target_anchor);
                let is_carry_over = seen_anchors.contains(&item.target_anchor);
                if is_anchor_here
                    || is_carry_over
                    || (page_chunks.is_empty() && this_page_tosafot.len() < max_commentary_lines)
                {
                    this_page_tosafot.push(item);
                } else {
                    unplaced_tosafot.push_back(item);
                }
            }
            remaining_tosafot = unplaced_tosafot;

            let effective_max_tosafot_lines = if gemara_h > 0.0
                && gemara_h < math.content_height_pt * 0.5
                && !page_rashi_lines.is_empty()
            {
                ((gemara_h / config.commentary_line_height).floor() as usize)
                    .max(rashi_line_counter)
                    .min(max_commentary_lines)
            } else {
                max_commentary_lines
            };
            let tosafot_narrow_lines = if current_rashi_y > 0.0
                && current_rashi_y < math.content_height_pt * 0.5
            {
                (current_rashi_y / config.commentary_line_height).ceil() as usize
            } else {
                effective_max_tosafot_lines
            };

            let mut current_tosafot_y = 0.0f32;
            for (p_idx, item) in this_page_tosafot.into_iter().enumerate() {
                let start_line = tosafot_line_counter;
                let natural_y =
                    current_tosafot_y.max(start_line as f32 * config.commentary_line_height);

                let t_profile = if start_line < tosafot_narrow_lines
                    && tosafot_narrow_lines < effective_max_tosafot_lines
                {
                    crate::knuth_plass::MeasureProfile::l_shape(
                        tosafot_narrow_lines - start_line,
                        math.outer_column_width_pt,
                        math.content_width_pt,
                    )
                } else {
                    tosafot_profile.clone()
                };

                let p_node = ParagraphNode::new(
                    FractionalIndex::new(format!("t_{}_{}", page_number, p_idx)),
                    "tosafot",
                    &item.text,
                );
                let mut p_lines = engine.typeset_paragraph_shaped(
                    &p_node,
                    &config.commentary_font_family,
                    &t_profile,
                    config.commentary_font_size,
                    config.commentary_line_height,
                );

                if tosafot_line_counter + p_lines.len() > effective_max_tosafot_lines {
                    let available_lines =
                        effective_max_tosafot_lines.saturating_sub(tosafot_line_counter);
                    if let Some(take) =
                        calculate_typographic_split(p_lines.len(), available_lines, 2, 2)
                    {
                        let this_lines = p_lines[..take].to_vec();
                        let remainder_lines = &p_lines[take..];
                        let remainder_text = remainder_lines
                            .iter()
                            .map(|l| l.text.as_str())
                            .collect::<Vec<_>>()
                            .join(" ");
                        remaining_tosafot.push_front(CoPaginatedCommentary {
                            target_anchor: item.target_anchor.clone(),
                            text: remainder_text,
                        });
                        p_lines = this_lines;
                    } else if !page_tosafot_lines.is_empty() {
                        remaining_tosafot.push_front(item);
                        break;
                    }
                }

                for (idx, line) in p_lines.iter_mut().enumerate() {
                    line.line_index = start_line + idx;
                    line.baseline_y += natural_y;
                }

                if let Some(&(_, g_y)) = tentative_gemara_anchors.get(&item.target_anchor) {
                    let sync = ActiveSynchronizer::evaluate_and_remedy(
                        sync_config,
                        &item.target_anchor,
                        g_y,
                        "tosafot",
                        natural_y,
                    );
                    if let SyncRemedy::VerticalSpringApplied { spring_pt } = sync.remedy {
                        let max_room = (math.content_height_pt
                            - (natural_y + p_lines.len() as f32 * config.commentary_line_height))
                            .max(0.0);
                        ActiveSynchronizer::apply_spring_offset(
                            &mut p_lines,
                            spring_pt.min(max_room),
                        );
                    }
                    sync_results.push(sync);
                }

                current_tosafot_y = p_lines.last().map(|l| l.baseline_y).unwrap_or(natural_y);
                tosafot_line_counter += p_lines.len();
                page_tosafot_lines.extend(p_lines);
            }

            // 4b. Typeset additional commentary streams (e.g. Targum, Ramban)
            let mut page_additional_lines: HashMap<FlowId, Vec<LineBox>> = HashMap::new();
            for col in &math.columns {
                let fid = FlowId::new(&col.stream_id);
                if fid.0 == "main" || fid.0 == "rashi" || fid.0 == "tosafot" {
                    continue;
                }

                let col_queue = remaining_additional.entry(fid.clone()).or_default();
                let mut this_page_items = Vec::new();
                let mut unplaced_items = VecDeque::new();

                while let Some(item) = col_queue.pop_front() {
                    let is_anchor_here = tentative_gemara_anchors.contains_key(&item.target_anchor);
                    let is_carry_over = seen_anchors.contains(&item.target_anchor);
                    if is_anchor_here
                        || is_carry_over
                        || (page_chunks.is_empty() && this_page_items.len() < max_commentary_lines)
                    {
                        this_page_items.push(item);
                    } else {
                        unplaced_items.push_back(item);
                    }
                }
                *col_queue = unplaced_items;

                let stream_profile = math.create_measure_profile(config, &col.stream_id, None);
                let mut col_lines: Vec<LineBox> = Vec::new();
                let mut stream_line_counter = 0;
                let mut current_stream_y = 0.0f32;

                for (p_idx, item) in this_page_items.into_iter().enumerate() {
                    let start_line = stream_line_counter;
                    let natural_y =
                        current_stream_y.max(start_line as f32 * config.commentary_line_height);

                    let p_node = ParagraphNode::new(
                        FractionalIndex::new(format!(
                            "{}_{}_{}",
                            col.stream_id, page_number, p_idx
                        )),
                        &col.stream_id,
                        &item.text,
                    );
                    let mut p_lines = engine.typeset_paragraph_shaped(
                        &p_node,
                        &config.commentary_font_family,
                        &stream_profile,
                        config.commentary_font_size,
                        config.commentary_line_height,
                    );

                    if stream_line_counter + p_lines.len() > max_commentary_lines {
                        let available_lines =
                            max_commentary_lines.saturating_sub(stream_line_counter);
                        if let Some(take) =
                            calculate_typographic_split(p_lines.len(), available_lines, 2, 2)
                        {
                            let this_lines = p_lines[..take].to_vec();
                            let remainder_lines = &p_lines[take..];
                            let remainder_text = remainder_lines
                                .iter()
                                .map(|l| l.text.as_str())
                                .collect::<Vec<_>>()
                                .join(" ");
                            col_queue.push_front(CoPaginatedCommentary {
                                target_anchor: item.target_anchor.clone(),
                                text: remainder_text,
                            });
                            p_lines = this_lines;
                        } else if !col_lines.is_empty() {
                            col_queue.push_front(item);
                            break;
                        }
                    }

                    for (idx, line) in p_lines.iter_mut().enumerate() {
                        line.line_index = start_line + idx;
                        line.baseline_y += natural_y;
                    }

                    if let Some(&(_, g_y)) = tentative_gemara_anchors.get(&item.target_anchor) {
                        let sync = ActiveSynchronizer::evaluate_and_remedy(
                            sync_config,
                            &item.target_anchor,
                            g_y,
                            &col.stream_id,
                            natural_y,
                        );
                        if let SyncRemedy::VerticalSpringApplied { spring_pt } = sync.remedy {
                            let max_room = (math.content_height_pt
                                - (natural_y
                                    + p_lines.len() as f32 * config.commentary_line_height))
                                .max(0.0);
                            ActiveSynchronizer::apply_spring_offset(
                                &mut p_lines,
                                spring_pt.min(max_room),
                            );
                        }
                        sync_results.push(sync);
                    }

                    current_stream_y = p_lines.last().map(|l| l.baseline_y).unwrap_or(natural_y);
                    stream_line_counter += p_lines.len();
                    col_lines.extend(p_lines);
                }

                page_additional_lines.insert(fid, col_lines);
            }

            // Count expanded lines in Rashi
            let rashi_expanded_count = page_rashi_lines
                .iter()
                .enumerate()
                .filter(|(idx, line)| {
                    *idx >= rashi_narrow_lines || line.width > math.inner_column_width_pt + 1.0
                })
                .count();

            // 5. Build physical page frames matching SpreadMathematics
            let mut frames = Vec::new();
            for col in &math.columns {
                let lines = match col.stream_id.as_str() {
                    "main" => tentative_gemara_lines.clone(),
                    "rashi" => page_rashi_lines.clone(),
                    "tosafot" => page_tosafot_lines.clone(),
                    _ => page_additional_lines
                        .get(&FlowId::new(&col.stream_id))
                        .cloned()
                        .unwrap_or_default(),
                };

                frames.push(TextFrameBox {
                    frame_id: format!("frame_{}_{}", page_number, col.stream_id),
                    flow_id: col.stream_id.clone(),
                    rect: PhysicalRect::new(col.x_pt, col.y_pt, col.width_pt, col.max_height_pt),
                    lines,
                });
            }

            // 6. Balance shared column heights across active parallel frames on this page
            super::height_balance::SharedColumnHeightBalancer::balance_page_frames(
                &mut frames,
                &super::height_balance::HeightBalanceConfig::default(),
            );

            let page_layout = PageLayoutBox {
                page_index: page_number - 1,
                page_number_gematria: crate::gematria::GematriaEngine::to_hebrew_numeral(
                    page_number,
                ),
                dimensions: PhysicalRect::new(
                    0.0,
                    0.0,
                    config.page_width_pt,
                    config.page_height_pt,
                ),
                frames,
                break_token: None,
            };

            total_gemara_lines += tentative_gemara_lines.len();
            total_rashi_lines += page_rashi_lines.len();
            total_tosafot_lines += page_tosafot_lines.len();

            let mut page_stream_lines: HashMap<FlowId, usize> = HashMap::new();
            page_stream_lines.insert(FlowId::new("main"), tentative_gemara_lines.len());
            page_stream_lines.insert(FlowId::new("rashi"), page_rashi_lines.len());
            page_stream_lines.insert(FlowId::new("tosafot"), page_tosafot_lines.len());
            for (fid, lines) in &page_additional_lines {
                page_stream_lines.insert(fid.clone(), lines.len());
                *total_stream_lines.entry(fid.clone()).or_insert(0) += lines.len();
            }
            *total_stream_lines.entry(FlowId::new("main")).or_insert(0) +=
                tentative_gemara_lines.len();
            *total_stream_lines.entry(FlowId::new("rashi")).or_insert(0) += page_rashi_lines.len();
            *total_stream_lines
                .entry(FlowId::new("tosafot"))
                .or_insert(0) += page_tosafot_lines.len();

            pages.push(CoPaginatedPage {
                page_number,
                page_layout,
                math,
                gemara_lines_count: tentative_gemara_lines.len(),
                rashi_lines_count: page_rashi_lines.len(),
                tosafot_lines_count: page_tosafot_lines.len(),
                rashi_expanded_lines_count: rashi_expanded_count,
                sync_results,
                stream_lines_count: page_stream_lines,
            });

            page_number += 1;
        }

        CoPaginationResult {
            total_pages: pages.len(),
            pages,
            total_gemara_lines,
            total_rashi_lines,
            total_tosafot_lines,
            total_stream_lines,
            all_anchors_remedied,
        }
    }
}

